/** Оценка приёма 0–100: ok = 1, partial = 0.5, fail = 0, na не учитывается */
export function score(v: Visit): number {
  const xs = v.checks.filter((c) => c.mark !== 'na')
  const s = xs.reduce((a, c) => a + (c.mark === 'ok' ? 1 : c.mark === 'partial' ? 0.5 : 0), 0)
  return Math.round((s / xs.length) * 100)
}

export const doctorOf = (v: Visit) => doctors.find((d) => d.id === v.doctorId)!

/** Доля речи врача, % — по количеству слов */
export function talkShare(v: Visit): number {
  let d = 0, all = 0
  for (const l of v.lines) {
    const w = l.text.split(/\s+/).length
    all += w
    if (l.s === 'doc') d += w
  }
  return Math.round((d / all) * 100)
}
